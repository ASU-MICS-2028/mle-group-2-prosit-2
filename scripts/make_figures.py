def catalogue_path():
    return C.REPORTS / "FIGURES.md"
T2_MODELS = ["logreg", "lit_logreg", "lit_mlp", "random_forest", "lightgbm", "decision_tree", "knn", "svm_rbf"]


class Registry:
    def __init__(self) -> None:
        self.rows: list[dict[str, str]] = []

    def add(self, fig, name: str, section: str, caption: str, defends: str) -> None:
        save_figure(fig, name)
        plt.close(fig)
        self.rows.append({"section": section, "name": name, "caption": caption, "defends": defends})
        console.info(f"✓ {name}")

    def write(self) -> None:
        lines = [
            "# Figure catalogue\n",
            "Generated by `python -m scripts.make_figures` (and `scripts/make_eda_report.py` for the EDA figures, "
            "described in [EDA_REPORT.md](EDA_REPORT.md)). Each figure says what it shows and which claim it defends; "
            "use it to build the report, the slides and the Q&A.\n",
        ]
        for section in dict.fromkeys(r["section"] for r in self.rows):
            lines.append(f"\n## {section}\n\n| Figure | What it shows | Claim it defends |\n| --- | --- | --- |\n")
            for r in (r for r in self.rows if r["section"] == section):
                lines.append(f"| [`{r['name']}`](figures/{r['name']}.png) | {r['caption']} | {r['defends']} |\n")
        catalogue_path().write_text("".join(lines), encoding="utf-8")


def _preds(task: str, model: str, scheme: str) -> pd.DataFrame | None:
    path = C.PREDS / f"{task}_{model}_{scheme}.parquet"
    return pd.read_parquet(path) if path.exists() else None


def main() -> None:
    console.setup()
    reg = Registry()
    df = load_features()
    train = df[df["split"] == "train"].reset_index(drop=True)
    cost = cost_matrix_threshold()
    thr = cost["threshold"]
    groups = train.set_index("ID")["customer_id"]

    # ------------------------------------------------------------- preprocessing
    console.title("Figures: preprocessing")
    reg.add(plot_raw_vs_log(np.expm1(train["log_amount_usd"]), "Loan amount (USD)"), "pre_log_amount",
            "1. Preprocessing", "Amounts before and after log(1 + x).",
            "Log-transforming money columns and the Task 1 target (heavy right tail).")
    miss = train[["days_since_last_loan", "past_default_rate", "days_since_last_default"]].isna().mean().sort_values()
    reg.add(plot_counts(miss * 100, "Share of Train rows where a history feature is empty (%)", "% of rows"), "pre_missing_history",
            "1. Preprocessing", "How often each history feature has no value (no earlier loan / no earlier default).",
            "Median imputation plus a missing-indicator: 'empty' means 'no such event yet', which is itself informative.")

    # ------------------------------------------------------------- validation
    console.title("Figures: validation")
    summary = summarize_predictions_dir(threshold=thr)
    t2 = summary[(summary["task"] == "task2") & (summary["model"] != "majority")]
    if not t2.empty:
        reg.add(plot_scheme_comparison(t2, "pr_auc"), "val_scheme_pr_auc", "2. Validation",
                "PR-AUC of every model under random, by-customer and by-time validation.",
                "Random folds inflate scores (LightGBM 0.30 vs 0.19 by customer); by-time is the honest deployment estimate (D-7).")
        reg.add(plot_scheme_comparison(t2, "roc_auc"), "val_scheme_roc_auc", "2. Validation",
                "ROC-AUC under the three schemes.", "All models lose most of their ranking power on 2023+ loans: the population drifted.")

    # ------------------------------------------------------------- evaluation, Task 2
    console.title("Figures: evaluation (task 2)")
    oof = {m: p for m in T2_MODELS if (p := _preds("task2", m, "fold_group")) is not None}
    if oof:
        y = next(iter(oof.values()))["y_true"].to_numpy()
        raw = {m: p["y_pred"].to_numpy() for m, p in oof.items()}
        cal = {m: calibrate_oof(p["y_true"], p["y_pred"], p["fold"], method="platt") for m, p in oof.items()}
        top = [m for m in ("logreg", "lit_mlp", "random_forest", "lightgbm") if m in raw]
        reg.add(plot_pr_curves(y, {m: raw[m] for m in top}), "eval_pr_curves", "3. Evaluation: default model",
                "Precision-recall curves, GroupKFold out-of-fold.", "Every model is far above the no-skill line (1.8%).")
        reg.add(plot_roc_curves(y, {m: raw[m] for m in top}), "eval_roc_curves", "3. Evaluation: default model",
                "ROC curves, GroupKFold out-of-fold.", "Defaulters rank above payers about 85% of the time.")
        fig, axes = plt.subplots(1, 2, figsize=(11, 4.2))
        plot_reliability(y, {f"{m} raw": raw[m] for m in top[:2]}, ax=axes[0])
        axes[0].set_title("Before calibration")
        plot_reliability(y, {f"{m} Platt": cal[m] for m in top[:2]}, ax=axes[1])
        axes[1].set_title("After Platt calibration")
        fig.tight_layout()
        reg.add(fig, "eval_reliability_before_after", "3. Evaluation: default model",
                "Predicted vs actual default rate, raw and Platt-calibrated.",
                "Class weights inflate raw scores; the cost threshold is applied only to calibrated probabilities.")

        rows = []
        for m in oof:
            ci = bootstrap_ci(y, cal[m], threshold=thr, groups=groups.loc[oof[m]["ID"]].to_numpy(), n_boot=200)
            rows.append({"model": m, **ci})
        ci_df = pd.DataFrame(rows)
        ci_df.to_csv(C.TABLES / "task2_bootstrap_ci.csv", index=False)
        base = float(np.mean(y))
        reg.add(plot_interval_forest(ci_df, "pr_auc", "pr_auc_ci_low", "pr_auc_ci_high", "model",
                                     "PR-AUC with 95% customer-level bootstrap intervals", ref=base + 0.0263),
                "eval_model_intervals", "3. Evaluation: default model",
                "PR-AUC and 95% interval per model (resampling customers).",
                "Every model beats the baseline beyond the noise floor; the top models' intervals overlap, so a simpler model is defensible.")

        sens = cost_sensitivity_table()
        reg.add(plot_cost_sensitivity(sens), "eval_cost_sensitivity", "3. Evaluation: default model",
                "Operating threshold under each recovery and future-loss assumption (configs/cost_matrix.yaml).",
                "How the decision rule moves with the business assumptions (brief Appendix A: at least two alternatives).")
        deployed = load_bundle()["clf_bundle"]["model_name"]
        p_dep = cal.get(deployed, next(iter(cal.values())))
        sweep = sweep_thresholds(y, p_dep, c_fp=cost["c_fp"], c_fn=cost["c_fn"])
        reg.add(plot_threshold_sweep(sweep, thr), "eval_threshold_sweep", "3. Evaluation: default model",
                f"Expected cost per loan and approval rate vs threshold ({deployed}, calibrated).",
                "The chosen threshold minimises expected cost under the draft cost matrix.")
        m = classification_metrics(y, p_dep, thr)
        reg.add(plot_confusion(m["tn"], m["fp"], m["fn"], m["tp"], f"{deployed} at threshold {thr:.3f}"), "eval_confusion_matrix",
                "3. Evaluation: default model", "Approved/declined vs repaid/defaulted at the operating threshold.",
                "What the decision rule does to real borrowers: defaults caught vs good borrowers turned away.")
        tenure = np.where(oof[deployed]["is_new_borrower"].to_numpy() == 1, "new", "repeat") if deployed in oof else None
        if tenure is not None:
            reg.add(plot_calibration_by_group(y, p_dep, tenure), "eval_calibration_by_tenure", "3. Evaluation: default model",
                    f"Mean predicted vs actual default rate for new and repeat borrowers ({deployed}).",
                    "Whether one calibration fits both groups; a gap here is why the deployed model is under review (#51).")

    # ------------------------------------------------------------- evaluation, Task 1
    console.title("Figures: evaluation (task 1)")
    for model in ("lightgbm_reg", "ridge"):
        if (p := _preds("task1", model, "fold_group")) is None:
            continue
        reg.add(plot_pred_vs_actual(p["y_true"], p["y_pred"], title=f"{model}: predicted vs actual"), f"t1_pred_vs_actual_{model}",
                "4. Evaluation: loan-amount model", "Predicted vs actual amount (log USD), GroupKFold.",
                "How much of the loan size the inputs can explain (R² about 0.2 by customer).")
        reg.add(plot_residuals_vs_fitted(p["y_true"], p["y_pred"], title=f"{model}: residuals"), f"t1_residuals_{model}",
                "4. Evaluation: loan-amount model", "Residuals vs fitted (log scale).", "Errors are centred on zero; spread is wide (brief: residual diagnostics).")
        reg.add(plot_error_by_decile(p["y_true"], p["y_pred"], title=f"{model}: error by loan size"), f"t1_error_by_decile_{model}",
                "4. Evaluation: loan-amount model", "Median absolute error as % of the loan, by actual-size decile.",
                "Limits are pulled to the middle: small loans are over-predicted, large loans under-predicted.")

    # ------------------------------------------------------------- interpretation
    console.title("Figures: interpretation")
    bundle = load_bundle()
    pipe = bundle["clf_bundle"]["pipeline"]
    names = pipe.named_steps["pre"].get_feature_names_out()
    est = pipe.named_steps["est"]
    if hasattr(est, "coef_"):
        reg.add(plot_coefficients(names, est.coef_), "interp_coefficients", "5. Interpretation",
                "Largest logistic-regression weights on standardized inputs (deployed model).",
                "Which factors push risk up or down overall; the basis of the reason codes (#22).")
    try:
        import shap

        from src.models import build_estimator
        from src.processing import get_feature_lists, make_preprocessor

        num, cat = get_feature_lists("task2")
        sample = train.sample(min(6000, len(train)), random_state=C.SEED)
        pre = make_preprocessor("task2")
        Xs = pre.fit_transform(train[num + cat])
        y_all = train["target"].astype(int).to_numpy()
        lgb = build_estimator("lightgbm", "task2", pos_weight=float((y_all == 0).sum() / max((y_all == 1).sum(), 1))).fit(Xs, y_all)
        sv = shap.TreeExplainer(lgb).shap_values(pre.transform(sample[num + cat]))
        sv = sv[1] if isinstance(sv, list) else sv
        reg.add(plot_shap_importance(pre.get_feature_names_out(), sv), "interp_shap_lightgbm", "5. Interpretation",
                "Mean |SHAP| per feature for LightGBM (6,000-loan sample).",
                "Top drivers are the lender's funding share and the calendar month, which both encode the period (2022 vs 2023+), then borrower history: part of the score tracks time, not the borrower (#22, ablation #52).")
    except Exception as exc:  # SHAP is optional for the rest of the figures
        console.info(f"SHAP skipped: {exc}")

    # ------------------------------------------------------------- fairness
    console.title("Figures: fairness")
    if deployed in oof:
        fair = oof[deployed].assign(y_pred=p_dep).merge(train[["ID", "log_amount_usd"]], on="ID")
        fair["loan_size_band"] = add_loan_size_band(fair)
        fair["tenure"] = np.where(fair["is_new_borrower"] == 1, "new", "repeat")
        for col in ("tenure", "lender_id", "loan_type", "loan_size_band"):
            t = disaggregated_evaluation(fair, col, threshold=thr)
            if col == "loan_type":
                t = t.head(8)
            t.to_csv(C.TABLES / f"fairness_{col}.csv", index=False)
            reg.add(plot_group_selection_rates(t), f"fair_selection_{col}", "6. Fairness",
                    f"Approval rate vs actual default rate by {col} ({deployed}, calibrated, GroupKFold).",
                    "Whether approval gaps track real risk differences or exceed them (Part D; mitigation in #50).")

    # ------------------------------------------------------------- transfer
    console.title("Figures: transfer")
    test = df[df["split"] == "test"].reset_index(drop=True)
    for feat in ("log_amount_usd", "duration", "n_past_loans"):
        reg.add(plot_feature_shift(test, feat), f"shift_{feat}", "7. Kenya to Ghana transfer",
                f"{feat}: Kenya vs Ghana Test rows.", "Ghana is a different population (larger, longer loans).")
    dom = run_domain_classifier(test)
    reg.add(plot_domain_scores(dom["oof_ghana_prob"], test["country_id"].eq("Ghana"), dom["domain_roc_auc"]), "shift_domain_scores",
            "7. Kenya to Ghana transfer", "Out-of-fold P(Ghana) from a Kenya-vs-Ghana classifier on behaviour features.",
            "Near-perfect separation means Ghana predictions are extrapolation (Part C).")
    reg.add(plot_shift_drivers(dom["top_shift_drivers"]), "shift_drivers", "7. Kenya to Ghana transfer",
            "Features that most separate Ghana from Kenya.",
            "The top driver is `n_past_labelled` = 0 for all of Ghana: a data artefact, not behaviour.")

    # ------------------------------------------------------------- product
    console.title("Figures: product")
    scores = score_frame(test, bundle=bundle, explain_sample=1500)
    summ = scores.groupby("country_id").agg(
        applications=("ID", "size"),
        mean_p_default=("probability_of_default", "mean"),
        approve=("decision", lambda s: (s == "approve").mean()),
        limit=("decision", lambda s: (s == "limit").mean()),
        decline=("decision", lambda s: (s == "decline").mean()),
        needs_review=("needs_review", "mean"),
    ).reset_index()
    summ.to_csv(C.TABLES / "product_decisions_by_country.csv", index=False)
    reg.add(plot_decision_mix(scores), "app_decision_mix", "8. The product in use",
            "Share of approve / limit / decline on Test applications, by country.",
            "What the deployed rule would do: in Ghana nothing is fully approved, a sign the Kenyan model does not transfer.")
    reg.add(plot_score_distribution(scores, thr), "app_score_distribution", "8. The product in use",
            "Calibrated P(default) on Test applications, by country, with the threshold.", "Ghana scores sit higher and wider than Kenya's.")
    reg.add(plot_limit_vs_request(scores), "app_limit_vs_request", "8. The product in use",
            "Requested amount vs model limit (USD) for approved or limited applications.",
            "The limit model predicts the typical amount, so about half of requests are cut; a cap should be a high quantile (#53).")
    reasons = scores["top_3_reasons"].dropna().explode().value_counts()
    reg.add(plot_counts(reasons, "Reasons given (1,500 sampled Test applications)", "times given"), "app_reason_frequency",
            "8. The product in use", "How often each plain-language reason appears.",
            "Reasons are about the borrower's own record and product; calendar and internal fields never appear.")
    flags = scores[["flag_country", "flag_lender", "flag_product", "flag_amount"]].sum().rename(lambda s: s.replace("flag_", ""))
    reg.add(plot_counts(flags, "Applications flagged for human review, by reason (Test)"), "app_review_flags", "8. The product in use",
            "Why applications are sent to a person.", "Every Ghana application is flagged: the system says when it is outside its evidence.")
    lat = benchmark_latency(n_calls=1000, return_samples=True)
    reg.add(plot_latency(lat["samples_ms"]), "app_latency", "8. The product in use",
            f"Time per scored application over 1,000 calls (median {lat['median_ms']:.0f} ms, p95 {lat['p95_ms']:.0f} ms).",
            "Fast enough for a mobile-money flow (brief Part E: latency).")
    pd.DataFrame([{k: v for k, v in lat.items() if k != "samples_ms"}]).to_csv(C.TABLES / "scorer_latency.csv", index=False)

    reg.write()
    console.done(f"{len(reg.rows)} figures in {C.rel(C.FIGURES)}; catalogue {C.rel(catalogue_path())}")


if __name__ == "__main__":
    main()
